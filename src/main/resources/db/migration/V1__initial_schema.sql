CREATE TABLE categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE, color VARCHAR(7) NOT NULL
);
CREATE TABLE expenses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL, description VARCHAR(1000),
 kind VARCHAR(20) NOT NULL CHECK (kind IN ('BILL','SUBSCRIPTION')),
 category_id BIGINT NOT NULL REFERENCES categories(id),
 amount NUMERIC(12,2) NOT NULL CHECK (amount > 0), currency VARCHAR(3) NOT NULL,
 frequency VARCHAR(20) NOT NULL CHECK (frequency IN ('WEEKLY','MONTHLY','QUARTERLY','YEARLY','CUSTOM')),
 custom_interval INTEGER, custom_unit VARCHAR(20),
 start_date DATE NOT NULL, next_due_date DATE NOT NULL, end_date DATE,
 payment_method VARCHAR(120), website_url VARCHAR(500),
 status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE','PAUSED','CANCELED')),
 variable_amount BOOLEAN NOT NULL, notes VARCHAR(2000), version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK (next_due_date >= start_date), CHECK (end_date IS NULL OR end_date >= next_due_date),
 CHECK (frequency <> 'CUSTOM' OR (custom_interval > 0 AND custom_unit IN ('DAYS','WEEKS','MONTHS','YEARS')))
);
CREATE INDEX ix_expenses_due ON expenses(status,next_due_date);
CREATE TABLE payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_id BIGINT NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
 occurrence_date DATE NOT NULL, payment_date DATE NOT NULL,
 amount NUMERIC(12,2) NOT NULL CHECK(amount > 0), currency VARCHAR(3) NOT NULL, notes VARCHAR(2000),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT uq_payment_occurrence UNIQUE(expense_id,occurrence_date)
);
CREATE INDEX ix_payments_date ON payments(payment_date);
CREATE TABLE reminder_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_id BIGINT NOT NULL UNIQUE REFERENCES expenses(id) ON DELETE CASCADE,
 days_before INTEGER NOT NULL CHECK(days_before BETWEEN 0 AND 90), enabled BOOLEAN NOT NULL
);
CREATE TABLE notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_id BIGINT NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
 occurrence_date DATE NOT NULL, message VARCHAR(500) NOT NULL, read BOOLEAN NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT uq_notification_occurrence UNIQUE(expense_id,occurrence_date)
);
CREATE TABLE app_settings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 currency VARCHAR(3) NOT NULL, theme VARCHAR(10) NOT NULL, reminder_days INTEGER NOT NULL CHECK(reminder_days BETWEEN 0 AND 90)
);
